#!/usr/bin/env python3
"""Writes crates/calendar-ical/src/{grapheme_tables.rs,zone_data.rs} from what Foundation and Swift answer on this Mac.

Usage (from the repository root, on macOS with swiftc):
    python3 scripts/dev/ical-tables/generate.py

The grapheme tables are the character-break classes `String.count` observes (the calendar-ical crate has no Unicode
segmentation crate); the zone data is `TimeZone.knownTimeZoneIdentifiers` and the abbreviations Foundation reports for
the zones where it does not write `GMT+h` (`GMT+0` at zero). Both are inputs of `ICalendar` that Swift took from the operating system.
"""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent.parent / 'crates' / 'calendar-ical' / 'src'


def run_swift(source, name):
    with tempfile.TemporaryDirectory() as tmp:
        binary = pathlib.Path(tmp) / name
        subprocess.run(['swiftc', '-O', str(HERE / source), '-o', str(binary)], check=True)
        return subprocess.run([str(binary)], check=True, capture_output=True, text=True).stdout


def generic(seconds):
    if seconds == 0:
        return 'GMT+0'
    sign = '+' if seconds > 0 else '-'
    a = abs(seconds)
    minutes = (a % 3600) // 60
    return f'GMT{sign}{a // 3600}' + (f':{minutes:02d}' if minutes else '')


def main():
    header = '//! Generated by scripts/dev/ical-tables/generate.py; do not edit.\n\n'
    (OUT / 'grapheme_tables.rs').write_text(header + run_swift('grapheme-tables.swift', 'g'))
    rows = [line.split('\t') for line in run_swift('zone-names.swift', 'z').splitlines()]
    ids = [r[0] for r in rows]
    exceptions = []
    for ident, jan, jul, jan_dst, jul_dst, jan_off, jul_off in rows:
        samples = [(jan, jan_dst == 'true', int(jan_off)), (jul, jul_dst == 'true', int(jul_off))]
        if all(name == generic(off) for name, _, off in samples):
            continue
        std = next((n for n, dst, off in samples if not dst and n != generic(off)), '')
        dst = next((n for n, d, off in samples if d and n != generic(off)), '')
        exceptions.append((ident, std, dst))
    body = header
    body += '/// `TimeZone.knownTimeZoneIdentifiers`, sorted (macOS 27).\n'
    body += 'pub(crate) const KNOWN_IDENTIFIERS: &[&str] = &[\n' + ''.join(f'    "{i}",\n' for i in ids) + '];\n\n'
    body += ('/// Zones for which `abbreviation(for:)` (locale `en_US`) is not `GMT+h[:mm]`: the name outside and inside\n'
             '/// daylight time; an empty name means the generic form.\n')
    body += 'pub(crate) const ABBREVIATIONS: &[(&str, &str, &str)] = &[\n'
    body += ''.join(f'    ("{i}", "{s}", "{d}"),\n' for i, s, d in exceptions) + '];\n'
    (OUT / 'zone_data.rs').write_text(body)


if __name__ == '__main__':
    sys.exit(main())
